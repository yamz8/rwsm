#!/usr/bin/env python3
"""Writes the Unicode tables rwsm needs to behave like Python: the code
points repr() escapes (str.isprintable() is false) and the decimal digits
float() accepts. Both depend on the interpreter's Unicode version, so
build.rs runs this with the Python uwsm runs on ($RWSM_PYTHON, default
/usr/bin/python3) and falls back to src/unicode_tables.rs, made with:

    /usr/bin/python3 -I tools/gen-unicode-tables.py > src/unicode_tables.rs
"""
import sys
import unicodedata


def ranges(pred):
    out = []
    start = None
    for cp in range(0x110000):
        if pred(cp) and start is None:
            start = cp
        elif not pred(cp) and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def table(name, doc, items):
    print(f"/// {doc}")
    print("#[rustfmt::skip]")
    print(f"pub const {name}: &[(u32, u32)] = &[")
    for i in range(0, len(items), 4):
        print("    " + " ".join(f"(0x{a:X}, 0x{b:X})," for a, b in items[i : i + 4]))
    print("];")


nonprintable = ranges(lambda cp: not chr(cp).isprintable())

# Decimal digits come in runs of ten, 0 to 9; record each run.
digits = []
for start, end in ranges(lambda cp: unicodedata.decimal(chr(cp), None) is not None):
    for zero in range(start, end + 1, 10):
        assert [unicodedata.decimal(chr(zero + d)) for d in range(10)] == list(range(10))
        digits.append((zero, zero + 9))

v = sys.version_info
print(f"""// Unicode tables matching Python {v.major}.{v.minor}.{v.micro} (Unicode {unicodedata.unidata_version}).
// Generated by `tools/gen-unicode-tables.py`; do not edit.
""")
table("NONPRINTABLE", "Code points `repr()` escapes: sorted, inclusive ranges.", nonprintable)
print()
table("DECIMAL_DIGITS", "Runs of decimal digits `float()` accepts, each from 0 to 9.", digits)
