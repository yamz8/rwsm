#!/usr/bin/env python3
"""Writes src/nonprintable.rs: the code point ranges Python's repr() escapes
(str.isprintable() is false). The result depends on the Python's Unicode
version; regenerate with the Python that uwsm runs on:

    python3 -I tools/gen-nonprintable.py > src/nonprintable.rs
"""
import sys
import unicodedata

ranges = []
start = None
for cp in range(0x110000):
    printable = chr(cp).isprintable()
    if not printable and start is None:
        start = cp
    elif printable and start is not None:
        ranges.append((start, cp - 1))
        start = None
if start is not None:
    ranges.append((start, 0x10FFFF))

v = sys.version_info
print(f"""//! Code points Python's `repr()` escapes, i.e. where `str.isprintable()` is
//! false. Generated by `tools/gen-nonprintable.py` with Python
//! {v.major}.{v.minor}.{v.micro} (Unicode {unicodedata.unidata_version}); do not edit.

/// Sorted, non-overlapping inclusive ranges.
#[rustfmt::skip]
pub const RANGES: &[(u32, u32)] = &[""")
for i in range(0, len(ranges), 4):
    print("    " + " ".join(f"(0x{a:X}, 0x{b:X})," for a, b in ranges[i : i + 4]))
print("];")
